export const artistSearchQueries = (artist) => [
	...new Set([artist, ...(ALIASES[artist] ?? []), artist.split(/\s+/).at(-1)])
]
export const normalizeArtist = (value) =>
	value
		.normalize("NFD")
		.replace(/[\u0300-\u036f]/g, "")
		.toLowerCase()
		.replace(/[^a-z0-9]+/g, " ")
		.trim()
const prefixes = POPULAR_ARTISTS.flatMap((artist) =>
	[artist, ...(ALIASES[artist] ?? [])].map((alias) => ({
		artist,
		prefix: normalizeArtist(alias)
	}))
).sort((a, b) => b.prefix.length - a.prefix.length)

/** Only credit a named prefix; search results may contain unrelated titles. */
export function popularArtistForTitle(name) {
	const archiveCredits = [
		[/^JOHN\./i, "Elton John"],
		[/^BUSH\./i, "Kate Bush"],
		[/^STEVENS\./i, "Yusuf / Cat Stevens"],
		[/^MINOGUE\./i, "Kylie Minogue"],
		[/^C\.RICHARD\./i, "Cliff Richard"],
		[/^R\.ASTLEY\./i, "Rick Astley"],
		[/^J\.CASH\./i, "Johnny Cash"],
		[/^REM(?:[. -]|$)/i, "R.E.M."]
	]
	const credit = archiveCredits.find(([pattern]) => pattern.test(name))
	if (credit) {
		return credit[1]
	}
	const title = normalizeArtist(name.replace(/\.(mid|midi)$/i, ""))
	return prefixes.find(({ prefix }) => title === prefix || title.startsWith(`${prefix} `))?.artist
}